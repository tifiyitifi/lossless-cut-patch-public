import type { TFunction } from 'i18next';

import type { PatchIntent } from '../../../../common/features/patchCommand';
import { defaultPatchWorkDirName } from '../../../../common/features/patchWork';

/**
Console copy (fork-owned).

Kept out of the pure command table so every user-visible string is a literal `t()` key the i18n
scanner can find; the command data itself stays free of display text.
*/
export default function getCommandDescription(t: TFunction, intent: PatchIntent, workDirName = defaultPatchWorkDirName) {
  switch (intent) {
    case 'toggle-batch-files-list': {
      return t('Show or hide the source file list.');
    }
    case 'toggle-command-custom-settings': {
      return t('Open or close the command alias editor.');
    }
    case 'toggle-keyboard-practice': {
      return t('Turn keyboard practice mode on or off: keys explain themselves before they run.');
    }
    case 'toggle-work-settings': {
      return t('Open or close the working directory settings.');
    }
    case 'exportForce': {
      return t('Cut every selected result again instead of reusing the unchanged ones.');
    }
    case 'resumewindows': {
      return t('Reopen the cut-results and merged-result windows for the current file.');
    }
    case 'toggleclipswindow': {
      return t('Toggle the cut-results window.');
    }
    case 'togglemergedwindow': {
      return t('Toggle the merged-result window.');
    }
    case 'post-process-merge': {
      return t('Finish the job: move the source video, the merged result and the cut results out of the work area, then load the next video.');
    }
    case 'post-process-cut': {
      return t('Finish the job: move the source video and the cut results out of the work area, then load the next video.');
    }
    case 'open-workpath-list': {
      return t('Open the work folders where a {{name}} area was created, each with what every source became.', { name: workDirName });
    }
    case 'clear-empty-work-dirs': {
      return t('Clear empty work dirs: move every empty {{name}} folder to the recycle bin. Only known stage folders and the export manifest generated by the app are accepted; any other file or folder, even an empty one, is skipped. This cleanup does not delete any file. If the recycle bin is unavailable, nothing is deleted and the folder is left for you to handle.', { name: workDirName });
    }
    default: {
      return intent;
    }
  }
}
