// eslint-disable-next-line import-js/no-extraneous-dependencies
import { describe, expect, it } from 'vitest';

import { checksumAssetName, isSha256Hex, parseChecksumFile, pickChecksumAsset } from './checksums.js';

const digest = 'a'.repeat(64);
const other = 'b'.repeat(64);

describe('pickChecksumAsset', () => {
  it('finds the checksum index among the release assets', () => {
    const picked = pickChecksumAsset([
      { name: 'LosslessCut-Patch-win-x64.zip', url: 'z', size: 1 },
      { name: checksumAssetName, url: 'c', size: 129 },
    ]);
    expect(picked?.url).toBe('c');
  });

  it('is undefined when the release publishes no checksum index', () => {
    expect(pickChecksumAsset([{ name: 'LosslessCut-Patch-win-x64.zip', url: 'z', size: 1 }])).toBeUndefined();
  });
});

describe('parseChecksumFile', () => {
  it('reads the digest of the named package', () => {
    expect(parseChecksumFile(`${digest}  LosslessCut-Patch-win-x64.zip`, 'LosslessCut-Patch-win-x64.zip')).toBe(digest);
  });

  it('ignores the other packages in the same file', () => {
    const text = [
      `${other}  LosslessCut-Patch-win-x64.7z`,
      `${digest}  LosslessCut-Patch-win-x64.zip`,
    ].join('\n');
    expect(parseChecksumFile(text, 'LosslessCut-Patch-win-x64.zip')).toBe(digest);
  });

  it('tolerates CRLF, trailing spaces and a binary-mode star', () => {
    expect(parseChecksumFile(`${digest} *LosslessCut-Patch-win-x64.zip  \r\n`, 'LosslessCut-Patch-win-x64.zip')).toBe(digest);
  });

  it('matches the name case-insensitively, because Windows does', () => {
    expect(parseChecksumFile(`${digest}  losslesscut-patch-WIN-x64.zip`, 'LosslessCut-Patch-win-x64.zip')).toBe(digest);
  });

  it('normalizes an upper-case digest', () => {
    expect(parseChecksumFile(`${digest.toUpperCase()}  package.zip`, 'package.zip')).toBe(digest);
  });

  it('returns undefined when the package is not listed', () => {
    expect(parseChecksumFile(`${other}  LosslessCut-Patch-win-x64.7z`, 'LosslessCut-Patch-win-x64.zip')).toBeUndefined();
  });

  it('skips lines that are not a checksum entry', () => {
    const text = ['# generated by CI', '', 'not a digest  package.zip', `${digest}  package.zip`].join('\n');
    expect(parseChecksumFile(text, 'package.zip')).toBe(digest);
  });

  it('returns undefined for an empty or truncated file', () => {
    expect(parseChecksumFile('', 'package.zip')).toBeUndefined();
    expect(parseChecksumFile('a'.repeat(63), 'package.zip')).toBeUndefined();
  });
});

describe('isSha256Hex', () => {
  it('accepts exactly 64 hex characters', () => {
    expect(isSha256Hex(digest)).toBe(true);
    expect(isSha256Hex('A'.repeat(64))).toBe(false);
    expect(isSha256Hex('a'.repeat(63))).toBe(false);
    expect(isSha256Hex('z'.repeat(64))).toBe(false);
  });
});
